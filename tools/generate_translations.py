def fill_po_file(lang: str, translations: dict[str, str]) -> None:
    """Read a .po file and fill in msgstr for each matching msgid."""
    po_path = LOCALE_DIR / lang / "LC_MESSAGES" / "docking.po"
    if not po_path.exists():
        print(f"  SKIP {po_path} (not found)")
        return

    content = po_path.read_text(encoding="utf-8")

    for msgid, msgstr in translations.items():
        # Replace empty msgstr after the matching msgid
        # Pattern: msgid "X"\nmsgstr ""  ->  msgid "X"\nmsgstr "Y"
        escaped_id = re.escape(msgid)
        escaped_str = msgstr.replace("\\", "\\\\").replace('"', '\\"')
        pattern = rf'(msgid "{escaped_id}"\n)msgstr ""'
        replacement = rf'\1msgstr "{escaped_str}"'
        content = re.sub(pattern, replacement, content)

    po_path.write_text(content, encoding="utf-8")
    filled = sum(1 for m in re.finditer(r'msgstr "(?!").+?"', content))
    print(f"  {lang}: {filled} strings translated")


def main() -> None:
    for lang, translations in TRANSLATIONS.items():
        fill_po_file(lang=lang, translations=translations)


if __name__ == "__main__":
    main()
